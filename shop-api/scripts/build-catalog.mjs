// Builds lib/catalog.generated.ts from the site's _products/*.md front matter, so prices and
// download files have one source: the product pages. Runs on every Vercel build.
//   --unpublished  also include products marked `published: false` (tests, local checks)
// SHOP_INCLUDE_UNPUBLISHED=1 does the same on a Vercel preview deployment.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const here = dirname(fileURLToPath(import.meta.url));
const productsDir = join(here, '..', '..', '_products');
const out = join(here, '..', 'lib', 'catalog.generated.ts');
const includeUnpublished = process.argv.includes('--unpublished') || process.env.SHOP_INCLUDE_UNPUBLISHED === '1';

/** @param {unknown} v @param {string} where */
function cents(v, where) {
  if (v === undefined || v === null || v === '') return null;
  const n = Number(v);
  if (!Number.isFinite(n) || n <= 0) throw new Error(`${where}: price must be a positive number of dollars, got ${JSON.stringify(v)}`);
  return Math.round(n * 100);
}

const items = [];
for (const name of readdirSync(productsDir).filter((f) => f.endsWith('.md')).sort()) {
  const src = readFileSync(join(productsDir, name), 'utf8');
  const fm = src.match(/^---\n([\s\S]*?)\n---/);
  if (!fm) continue;
  const p = parse(fm[1]);
  if (p.published === false && !includeUnpublished) continue;
  const slug = basename(name, '.md');
  const shipped = p.kind !== 'digital';
  /** @type {Map<string, { file: string, bytes: number, sha256: string }>} */
  const downloads = new Map((p.downloads ?? []).map((d) => [d.file, { file: d.file, bytes: d.bytes, sha256: d.sha256 }]));
  // No `skus` list: the product is one item, keyed by its handle, with every download.
  const skus = p.skus ?? [{ key: p.handle, name: '', files: [...downloads.keys()] }];
  for (const s of skus) {
    const unitAmount = cents(s.price ?? p.price, `${name} ${s.key}`);
    if (unitAmount === null) continue; // no price: not for sale yet
    const files = (s.files ?? []).map((f) => {
      const d = downloads.get(f);
      if (!d) throw new Error(`${name} ${s.key}: ${f} is not in downloads`);
      return d;
    });
    if (!shipped && !files.length) throw new Error(`${name} ${s.key}: a digital item needs at least one file`);
    items.push({ key: s.key, product: p.title, name: s.name ?? '', url: `/shop/${slug}/`, unitAmount, shipped, files });
  }
}
const keys = items.map((i) => i.key);
const dup = keys.find((k, i) => keys.indexOf(k) !== i);
if (dup) throw new Error(`duplicate item key ${dup}`);

writeFileSync(out, `// Generated by scripts/build-catalog.mjs from _products/. Do not edit.
import type { Item } from './catalog.js';

export const items: Item[] = ${JSON.stringify(items, null, 2)};
`);
console.log(`catalog: ${items.length} item(s) for sale${includeUnpublished ? ' (including unpublished)' : ''}`);
